test("Hat mich im Ziel: echtes true zählt, secret true nicht", function()
  local ns = M.Load()
  M.AddEnemy("nameplate1", { name = "Jaeger", target = "player" })
  M.AddEnemy("nameplate2", { name = "Schatten", target = "player", targetsMeSecret = true })
  M.FireEvent("NAME_PLATE_UNIT_ADDED", "nameplate1")
  M.FireEvent("NAME_PLATE_UNIT_ADDED", "nameplate2")
  ok(ns.Tracker.Get("Jaeger-Forever").targetedMe)
  no(ns.Tracker.Get("Schatten-Forever").targetedMe)
  eq(#ns.Tracker.Targeters(6), 1)
  -- UNIT_TARGET later: he switches to me
  M.Advance(10)
  M.AddEnemy("nameplate3", { name = "Spaet" })
  M.FireEvent("NAME_PLATE_UNIT_ADDED", "nameplate3")
  no(ns.Tracker.Get("Spaet-Forever").targetedMe)
  M.units.nameplate3.target = "player"
  M.FireEvent("UNIT_TARGET", "nameplate3")
  ok(ns.Tracker.Get("Spaet-Forever").targetedMe)
  eq(#ns.Tracker.Targeters(6), 1, "Jaeger ist schon 10 s her")
end)

