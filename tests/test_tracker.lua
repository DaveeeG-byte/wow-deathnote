test("Gelisteter Feind: ENEMY_SPOTTED, lastSeen gedrosselt, Sichtungen", function()
  local ns = M.Load(); local S = ns.Store
  local k = S.AddManual("Staats", "Feind")
  M.AddEnemy("nameplate1", { name = "Staats", surname = "Feind", level = 42 })
  M.ClearFired()
  M.FireEvent("NAME_PLATE_UNIT_ADDED", "nameplate1")
  local sp = M.Fired("ENEMY_SPOTTED")
  eq(#sp, 1); eq(sp[1][2], k); eq(sp[1][3], "nameplate1"); eq(sp[1][4], "nameplate")
  local e = S.Get(k)
  eq(e.sightings, 1); eq(e.lastSeen.zone, "Schlingendorntal"); eq(e.lastSeen.x, 41.2); eq(e.level, 42)
  local t1 = e.lastSeen.t
  -- same frame: no duplicate event
  M.FireEvent("UPDATE_MOUSEOVER_UNIT")
  M.AddEnemy("mouseover", { name = "Staats", surname = "Feind" })
  M.FireEvent("UPDATE_MOUSEOVER_UNIT")
  eq(#M.Fired("ENEMY_SPOTTED"), 1, "gleicher Frame")
  M.Advance(2)
  M.FireEvent("UPDATE_MOUSEOVER_UNIT")
  eq(#M.Fired("ENEMY_SPOTTED"), 2, "nächster Frame feuert (A drosselt nicht)")
  eq(e.lastSeen.t, t1, "lastSeen höchstens alle 5 s")
  M.Advance(4)
  M.FireEvent("UPDATE_MOUSEOVER_UNIT")
  ok(e.lastSeen.t > t1)
  eq(e.sightings, 1, "gleiche Begegnung")
  M.Advance(120)
  M.FireEvent("UPDATE_MOUSEOVER_UNIT")
  eq(e.sightings, 2, "neue Begegnung nach Pause")
  eq(ns.Tracker.UnitFor(k), "mouseover")
end)

