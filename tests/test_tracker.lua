local M = require("mock_wow")
local test, eq, ok, no = M.test, M.eq, M.ok, M.no

test("Feindlicher Spieler auf Namensplakette landet im Puffer", function()
  local ns = M.Load()
  M.AddEnemy("nameplate1", { name = "Grimm", surname = "Bart", class = "ROGUE", guild = "Die Bösen" })
  M.FireEvent("NAME_PLATE_UNIT_ADDED", "nameplate1")
  local r = ns.Tracker.Get("Grimm-Bart")
  ok(r); eq(r.class, "ROGUE"); eq(r.guild, "Die Bösen"); eq(r.guid, "Player-93-Grimm"); eq(r.unit, "nameplate1")
  no(r.targetedMe)
  eq(ns.Tracker.ByGUID("Player-93-Grimm").key, "Grimm-Bart")
  eq(ns.Tracker.ByName("grimm").key, "Grimm-Bart")
end)

