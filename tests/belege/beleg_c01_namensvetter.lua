-- 1.2.1 nach der Jagd (H1): "fuer dich erledigt" (V) und "erlegt" (E) nur fuer den, der wirklich getoetet wurde.
-- Kennt der Tracker oder das eigene Buch den Getoeteten unter vollem Namen, zaehlt kein Vorname eines anderen.
-- Dazu N4: V mit e=1, dessen E nie ankam, meldet trotzdem genau einmal.
local H = dofile((arg[0]:match("^(.*)/") or ".") .. "/_kopf_c.lua")
local M = H.M
local G = "Die Testgilde"
local function art(W, von, k) return (H.typen(W, von)[k] or 0) end
local function welt() return H.welt({ "GUILD_KILL", "GUILD_UPDATED", "HUNT_BAGGED", "AVENGED" }) end

H.lauf("(1) Namensvetter, den der Tracker kennt: kein V, keine Meldung, kein Zaehler", function()
  local W = welt()
  local a = W.client("Anton", "Wurst", G, { fullSender = true })
  local b = W.client("Berta", "Senf", G, { fullSender = true })
  a.login(); b.login(); W.run(90)
  local key = H.tod(b, "Taeter", "Lamm"); W.run(10)
  M.AddEnemy("target", { name = "Taeter", surname = "Unschuld", guid = "Player-1-AAAA01" })
  a.fire("PLAYER_TARGET_CHANGED"); W.run(1)
  local r = a.ns.Tracker.ByGUID("Player-1-AAAA01")
  H.erwartet("Vorbedingung: der Tracker kennt ihn als Taeter-Unschuld", r and r.key == "Taeter-Unschuld", r and r.key)
  a.fire("PARTY_KILL", a.env.UnitGUID("player"), "Player-1-AAAA01"); W.run(10)
  H.erwartet("kein V fuer einen anderen Spieler", art(W, a, "V") == 0, art(W, a, "V"))
  H.erwartet("keine falsche Meldung 'fuer dich erledigt'", H.zaehle(b, "AVENGED") == 0, H.zaehle(b, "AVENGED"))
  H.erwartet("kein Zaehler 'geraecht' am echten Taeter", select(2, b.ns.Guild.Avenged(key)) == 0)
end)

H.lauf("(2) dasselbe bei 'erlegt' (E) und mit dem eigenen Buch als Quelle", function()
  local W = welt()
  local a = W.client("Anton", "Wurst", G, { fullSender = true })
  local b = W.client("Berta", "Senf", G, { fullSender = true })
  a.login(); b.login(); W.run(90)
  b.ns.Guild.Release("Taeter-Lamm", { to = "guild", why = "x" }); W.run(10)
  M.AddEnemy("target", { name = "Taeter", surname = "Unschuld", guid = "Player-1-AAAA01" })
  a.fire("PLAYER_TARGET_CHANGED"); W.run(1)
  a.fire("PARTY_KILL", a.env.UnitGUID("player"), "Player-1-AAAA01"); W.run(10)
  H.erwartet("kein E fuer einen anderen Spieler", art(W, a, "E") == 0, art(W, a, "E"))
  H.erwartet("keine Meldung 'erlegt'", H.zaehle(b, "HUNT_BAGGED") == 0)
  -- eigenes Buch kennt ihn (Tracker vergessen): ebenso nichts
  local W2 = welt()
  local a2 = W2.client("Anton", "Wurst", G, { fullSender = true })
  local b2 = W2.client("Berta", "Senf", G, { fullSender = true })
  a2.login(); b2.login(); W2.run(90)
  b2.ns.Guild.Release("Taeter-Lamm", { to = "guild", why = "x" }); W2.run(10)
  local k2 = a2.ns.Store.ApplyKill({ name = "Taeter", surname = "Unschuld", class = "MAGE", guid = "Player-1-AAAA02" },
    { t = time() - 50, zone = "Z", me = "Anton Wurst", source = "recap" }, true)
  H.erwartet("Vorbedingung: das eigene Buch kennt die GUID", a2.ns.Store.ByGUID("Player-1-AAAA02") == k2, k2)
  M.AddEnemy("nameplate7", { name = "Taeter", surname = "Unschuld", guid = "Player-1-AAAA02" })
  a2.fire("PARTY_KILL", a2.env.UnitGUID("player"), "Player-1-AAAA02"); W2.run(10)
  H.erwartet("eigenes Buch als Quelle: kein E", art(W2, a2, "E") == 0, art(W2, a2, "E"))
end)

H.lauf("(3) Gegenprobe: unbekannte GUID, Vorname eindeutig: E und V gehen wie bisher", function()
  local W = welt()
  local a = W.client("Anton", "Wurst", G, { fullSender = true })
  local b = W.client("Berta", "Senf", G, { fullSender = true })
  a.login(); b.login(); W.run(90)
  local key = H.tod(b, "Taeter", "Lamm"); W.run(10)
  b.ns.Guild.Release(key, { to = "guild", why = "x" }); W.run(10)
  M.AddEnemy("nameplate8", { name = "Taeter", guid = "Player-1-AAAA03" })   -- nur Vorname bekannt
  a.fire("PARTY_KILL", a.env.UnitGUID("player"), "Player-1-AAAA03"); W.run(10)
  H.erwartet("E geht", art(W, a, "E") == 1, art(W, a, "E"))
  H.erwartet("V geht", art(W, a, "V") == 1, art(W, a, "V"))
  H.erwartet("genau eine Meldung bei Berta (erlegt)", H.zaehle(b, "HUNT_BAGGED") + H.zaehle(b, "AVENGED") == 1)
end)

H.lauf("(4) N4: V mit e=1, das E kam nicht an (Deckel): trotzdem genau eine Meldung", function()
  local W = welt()
  local b = W.client("Berta", "Senf", G, { fullSender = true })
  local c = W.client("Carl", "Kurz", G, { fullSender = true })
  b.login(); c.login(); W.run(90)
  local key = H.tod(b, "Taeter", "Lamm"); W.run(10)
  c.ns.Guild.Release(key, { to = "guild", why = "x" }); W.run(10)
  local P = b.ns.Guild.Proto
  for i = 1, 3 do H.gilde(b, P.EncodeBagged(key, "Carl Kurz", time() - 150 * i), "Carl Kurz-Forever") end
  W.run(5)
  local vorher = H.zaehle(b, "HUNT_BAGGED") + H.zaehle(b, "AVENGED")
  local t = time()
  H.gilde(b, P.EncodeBagged(key, "Carl Kurz", t), "Carl Kurz-Forever")
  H.gilde(b, P.EncodeAvenged(key, "Carl Kurz", t, true), "Carl Kurz-Forever")
  W.run(10)
  local nachher = H.zaehle(b, "HUNT_BAGGED") + H.zaehle(b, "AVENGED")
  H.erwartet("genau eine Meldung fuer die Toetung", nachher - vorher == 1, nachher - vorher)
  -- und wenn das E ankommt: weiter genau eine (erlegt)
  M.Advance(700)
  local t2 = time()
  local v2 = H.zaehle(b, "HUNT_BAGGED") + H.zaehle(b, "AVENGED")
  H.gilde(b, P.EncodeBagged(key, "Carl Kurz", t2), "Carl Kurz-Forever")
  H.gilde(b, P.EncodeAvenged(key, "Carl Kurz", t2, true), "Carl Kurz-Forever")
  W.run(10)
  H.erwartet("E kam an: genau eine Meldung", H.zaehle(b, "HUNT_BAGGED") + H.zaehle(b, "AVENGED") - v2 == 1)
end)
H.fertig()
